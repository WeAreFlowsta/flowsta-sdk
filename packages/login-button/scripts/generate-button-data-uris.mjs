/**
 * Regenerates src/buttonDataUris.ts from assets/svg/*.svg.
 * Run after changing button artwork: node scripts/generate-button-data-uris.mjs
 *
 * Why data URIs: asset-path approaches (/node_modules/..., new URL +
 * import.meta.url) break in consumers' production bundles — see the
 * 2026-06-13 fix. Inlined URIs work in every framework, bundler,
 * script-tag, and SSR context, with no CDN dependency.
 */
import { readFileSync, writeFileSync, readdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const svgDir = join(root, "assets", "svg");

// Minimal URL-encoding for SVG data URIs (smaller than base64, gzips well)
function encodeSvg(svg) {
  return svg
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/#/g, "%23")
    .replace(/{/g, "%7B")
    .replace(/}/g, "%7D")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/\s+/g, " ");
}

const entries = [];
for (const file of readdirSync(svgDir).sort()) {
  const m = file.match(/^flowsta_signin_web_(\w+)_(\w+)\.svg$/);
  if (!m) continue;
  const variant = `${m[1]}-${m[2]}`;
  const svg = readFileSync(join(svgDir, file), "utf8").trim();
  entries.push(`  "${variant}": "data:image/svg+xml,${encodeSvg(svg)}",`);
}

const out = `/**
 * AUTO-GENERATED by scripts/generate-button-data-uris.mjs — do not edit.
 * Official "Sign in with Flowsta" buttons as inline data URIs (svgo-
 * optimized). See script header for why this replaces asset paths.
 */
export const BUTTON_DATA_URIS: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(join(root, "src", "buttonDataUris.ts"), out);
console.log(`wrote src/buttonDataUris.ts with ${entries.length} variants`);
